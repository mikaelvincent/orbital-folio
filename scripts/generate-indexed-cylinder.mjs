/** Offline specialization of the installed Three cylinder generator.
 * npm run geometry:generate; --check verifies the tracked artifact is current.
 * Only the identical cap-center emission/index are changed. No vertex welding,
 * quantization or geometry analysis runs in the visitor's browser.
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { transform } from 'esbuild';

const sourcePath = new URL(
  '../node_modules/three/src/geometries/CylinderGeometry.js',
  import.meta.url,
);
const outputPath = new URL(
  '../features/spacecraft/geometry/indexed-cylinder.generated.js',
  import.meta.url,
);
const source = await readFile(sourcePath, 'utf8');
const license = await readFile(
  new URL('../node_modules/three/LICENSE', import.meta.url),
  'utf8',
);
const noticePath = new URL(
  '../public/licenses/three-indexed-cylinder.txt',
  import.meta.url,
);
const notice =
  'Three.js CylinderGeometry — offline cap-center specialization\nSource: three/src/geometries/CylinderGeometry.js\n\n' +
  license;
const hash = createHash('sha256').update(source).digest('hex');
const emission =
  /for \( let x = 1; x <= radialSegments; x \+\+ \) \{([\s\S]*?)\n\t\t\t\}/g;
if (
  [...source.matchAll(emission)].length !== 1 ||
  !source.includes('const c = centerIndexStart + x;')
)
  throw new Error(
    'Installed cylinder source changed; inspect cap topology before updating this specialization.',
  );
const specialized = source
  .replace(/^import .*;\n/gm, '')
  .replace(emission, '$1')
  .replace('const c = centerIndexStart + x;', 'const c = centerIndexStart;')
  .replace(/export \{ CylinderGeometry \};/, '')
  .replace(
    'super();',
    `super();
    if (![radiusTop, radiusBottom, height, radialSegments, heightSegments, thetaStart, thetaLength].every(Number.isFinite)
      || radiusTop < 0 || radiusBottom < 0 || height <= 0 || radialSegments < 3 || heightSegments < 1)
      return new THREE.CylinderGeometry(radiusTop, radiusBottom, height, radialSegments, heightSegments, openEnded, thetaStart, thetaLength);`,
  );
const wrapper = `const types = new WeakMap();
export function indexedCylinderType(THREE) {
  if (types.has(THREE)) return types.get(THREE);
  const { BufferGeometry, Float32BufferAttribute, Vector3, Vector2 } = THREE;
  ${specialized}
  types.set(THREE, CylinderGeometry);
  return CylinderGeometry;
}`;
const { code } = await transform(wrapper, {
  loader: 'js',
  format: 'esm',
  target: 'es2022',
  legalComments: 'none',
});
const artifact = `/*! Generated by scripts/generate-indexed-cylinder.mjs. Do not edit.
 * Source: three/src/geometries/CylinderGeometry.js SHA-256 ${hash}
 * Lossless specialization: share only the constant center tuple of each cap.
 * Torso/rim seams, arithmetic, triangle order, groups and clone/copy stay intact.
 *
${license
  .trim()
  .split('\n')
  .map((line) => ' * ' + line)
  .join('\n')}
 */\n${code}`;
if (process.argv.includes('--check')) {
  if (
    (await readFile(outputPath, 'utf8')) !== artifact ||
    (await readFile(noticePath, 'utf8')) !== notice
  )
    throw new Error(
      'Indexed cylinder artifact is stale. Run npm run geometry:generate and verify exactness before shipping.',
    );
  console.log(
    'Indexed cylinder artifact matches its installed source and generator.',
  );
} else {
  await writeFile(outputPath, artifact);
  await mkdir(new URL('../public/licenses/', import.meta.url), {
    recursive: true,
  });
  await writeFile(noticePath, notice);
  console.log(
    `Generated indexed cylinder (source ${hash}, ${Buffer.byteLength(artifact)} bytes).`,
  );
}
